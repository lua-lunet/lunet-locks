#!/usr/bin/env sh
# Vendor Apache ECharts into assets/vendor: the pinned canonical copy, and
# with the `lock` argument, the sha256-named content-addressed copy plus the
# nginx fragment that redirects the plain asset path to the sha-named file
# served with a cache-immutable header. Idempotent on each step.
set -eu

here=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
root="$here/.."
vendor_dir="$root/assets/vendor"
canonical="$vendor_dir/echarts.min.js"
version="${ECHARTS_VERSION:?ECHARTS_VERSION is required}"
url="https://cdn.jsdelivr.net/npm/echarts@$version/dist/echarts.min.js"

mkdir -p "$vendor_dir"

if [ ! -s "$canonical" ]; then
    curl -fsSLo "$canonical" "$url"
fi

sha=$(shasum -a 256 "$canonical" | awk '{print $1}')

if [ "${1:-}" = "lock" ]; then
    locked="$vendor_dir/echarts.min.$sha.js"
    cp "$canonical" "$locked"

    fragment="$vendor_dir/nginx-vendor.conf"
    cat > "$fragment" <<EOF
# Generated by console/bin/vendor.sh (make vendor-lock) — do not hand-edit.
# The plain asset path redirects to the sha256-named copy; that copy is
# content-addressed and serves with a cache-immutable header.
location = /vendor/echarts.min.js {
    return 302 /vendor/echarts.min.$sha.js;
}

location ~ ^/vendor/echarts\.min\.[0-9a-f]+\.js$ {
    add_header Cache-Control "public, max-age=31536000, immutable";
}
EOF
    echo "locked: $(basename "$locked") + nginx-vendor.conf (sha256 $sha)"
fi

echo "sha256 of $(basename "$canonical"): $sha"
